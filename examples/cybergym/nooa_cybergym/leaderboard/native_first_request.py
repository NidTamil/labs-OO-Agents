"""Controller witness for one actual native primary model-gateway admission."""

from __future__ import annotations

import json
import re
from pathlib import Path

from xeus_cybergym.canonical import canonical_json


class NativeFirstRequestWitness:
    """Correlate a reserved native launch with durable same-attempt gateway rows.

    The launch ID is the campaign start intent, while model request IDs are
    generated by the gateway. Both are scoped to one trusted task/attempt.
    This witness checks gateway admission, not successful provider completion.
    """

    def __init__(
        self,
        *,
        launch_authority,
        attempt_id: str,
        model_audit: Path,
        policy_sha256: str,
        expected_model: str,
    ):
        manifest = getattr(launch_authority, "manifest", None)
        launch_dir = Path(getattr(launch_authority, "launch_dir", ""))
        audit = Path(model_audit)
        if (
            type(manifest) is not dict
            or type(manifest.get("task_id")) is not str
            or type(manifest.get("launch_id")) is not str
            or not callable(getattr(launch_authority, "_check_receipt", None))
            or not launch_dir.is_absolute()
            or launch_dir.is_symlink()
            or not launch_dir.is_dir()
            or type(attempt_id) is not str
            or not attempt_id
            or not audit.is_absolute()
            or audit.parent.is_symlink()
            or not audit.parent.is_dir()
            or type(policy_sha256) is not str
            or re.fullmatch(r"[a-f0-9]{64}", policy_sha256) is None
            or type(expected_model) is not str
            or not expected_model
        ):
            raise ValueError("frozen native first-request evidence identity required")
        self.launch = launch_authority
        self.attempt_id = attempt_id
        self.audit = audit
        self.policy_sha256 = policy_sha256
        self.expected_model = expected_model

    def observed(self, launch_id: str) -> bool:
        if launch_id != self.launch.manifest["launch_id"]:
            raise ValueError("campaign launch identity differs from native launch")
        receipt_path = self.launch.launch_dir / "launcher-receipt.json"
        if not receipt_path.exists() and not receipt_path.is_symlink():
            return False
        if receipt_path.is_symlink() or not receipt_path.is_file():
            raise RuntimeError("native launch receipt is linked or invalid")
        receipt_raw = receipt_path.read_bytes()
        if len(receipt_raw) > 1024 * 1024:
            raise RuntimeError("native launch receipt exceeds evidence limit")
        receipt = json.loads(receipt_raw)
        if canonical_json(receipt) != receipt_raw:
            raise RuntimeError("native launch receipt is not canonical")
        self.launch._check_receipt(receipt)
        if not self.audit.exists() and not self.audit.is_symlink():
            return False
        if self.audit.is_symlink() or not self.audit.is_file():
            raise RuntimeError("native model audit is linked or invalid")
        raw = self.audit.read_bytes()
        if len(raw) > 16 * 1024 * 1024:
            raise RuntimeError("native model audit exceeds witness limit")
        completed = raw.rsplit(b"\n", 1)[0] if not raw.endswith(b"\n") else raw[:-1]
        reservations: set[str] = set()
        for line in completed.split(b"\n"):
            if not line:
                continue
            try:
                event = json.loads(line)
            except (ValueError, UnicodeDecodeError):
                raise RuntimeError("native model audit contains malformed event") from None
            if type(event) is not dict:
                raise RuntimeError("native model audit contains malformed event")
            if (
                event.get("task_id") != self.launch.manifest["task_id"]
                or event.get("attempt_id") != self.attempt_id
                or event.get("role") != "primary"
                or event.get("requested_model") != self.expected_model
                or event.get("policy_sha256") != self.policy_sha256
                or type(event.get("request_id")) is not str
                or not event["request_id"]
            ):
                continue
            if event.get("event") == "request_reserved":
                reservations.add(event["request_id"])
            if event.get("event") == "attempt_started" and event["request_id"] in reservations:
                return True
        return False
